// scripts/mysql-schema.mjs
// Derive a MySQL schema from the D1/SQLite schema, and apply it.
//
// The D1 schema is the source of truth; MySQL is the deployment target on
// Hostinger. SQLite is permissive about TEXT primary keys and unique columns;
// InnoDB is not, so key/unique columns become VARCHAR and money becomes
// DECIMAL. Everything else stays as written.
//
// Usage:
//   node scripts/mysql-schema.mjs write   # emit src/db/schema.mysql.sql
//   node scripts/mysql-schema.mjs apply   # write + execute against MySQL

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));

export function toMysql(sql) {
  let out = sql;
  // MySQL has no CREATE VIEW IF NOT EXISTS, and these compatibility views
  // exist only for SQLite-era tooling.
  out = out.replace(/^CREATE VIEW IF NOT EXISTS .*?;\s*$/gims, '');
  // Types
  out = out.replace(/\bREAL\b/g, 'DECIMAL(10,2)');
  // SQLite's INTEGER is 64-bit; MySQL's INT is 32-bit. Epoch-millisecond
  // timestamps (better-auth writes those) overflow INT and get clamped, which
  // silently corrupts every createdAt/expiresAt — so INTEGER must become BIGINT.
  out = out.replace(/\bINTEGER\b/g, 'BIGINT');
  // Key/unique columns must be VARCHAR on InnoDB.
  out = out.replace(/\bTEXT PRIMARY KEY\b/g, 'VARCHAR(191) PRIMARY KEY');
  out = out.replace(/\bTEXT UNIQUE NOT NULL\b/g, 'VARCHAR(191) UNIQUE NOT NULL');
  out = out.replace(/\bTEXT UNIQUE\b/g, 'VARCHAR(191) UNIQUE');
  out = out.replace(/\bTEXT NOT NULL REFERENCES\b/g, 'VARCHAR(191) NOT NULL REFERENCES');
  out = out.replace(/\bTEXT REFERENCES\b/g, 'VARCHAR(191) REFERENCES');
  out = out.replace(/\bid TEXT NOT NULL\b/g, 'id VARCHAR(191) NOT NULL');
  out = out.replace(/\blocale TEXT NOT NULL\b/g, 'locale VARCHAR(16) NOT NULL');
  out = out.replace(/\bdate TEXT NOT NULL\b/g, 'date VARCHAR(32) NOT NULL');
  out = out.replace(/\bitem_type TEXT NOT NULL\b/g, 'item_type VARCHAR(64) NOT NULL');
  out = out.replace(/\bitem_id TEXT NOT NULL\b/g, 'item_id VARCHAR(191) NOT NULL');
  // Indexed non-key columns also have to be VARCHAR to fit InnoDB key limits.
  out = out.replace(/\bprintify_product_id TEXT NOT NULL\b/g, 'printify_product_id VARCHAR(191) NOT NULL');
  out = out.replace(/\bprintify_order_id TEXT\b/g, 'printify_order_id VARCHAR(191)');
  out = out.replace(/\bresource_id TEXT\b/g, 'resource_id VARCHAR(191)');
  // better-auth hands Kysely real Date objects for its timestamp fields. SQLite
  // stored those as epoch integers, but MySQL must hold them as DATETIME: given
  // a BIGINT column, mysql2 serialises the Date to 'YYYY-MM-DD …' and MySQL
  // takes the numeric prefix, silently storing the year (2026) as the value.
  for (const column of ['createdAt', 'updatedAt', 'expiresAt', 'accessTokenExpiresAt', 'refreshTokenExpiresAt']) {
    out = out.replace(new RegExp(`\\b${column} BIGINT`, 'g'), `${column} DATETIME(3)`);
  }
  // MySQL has no CREATE INDEX IF NOT EXISTS.
  out = out.replace(/CREATE INDEX IF NOT EXISTS/g, 'CREATE INDEX');
  return out;
}

/** Split a multi-statement SQL script into individual statements. */
export function splitStatements(sql) {
  return sql
    .split(/;\s*(?:\r?\n|$)/)
    .map((s) => s.replace(/^\s*(--[^\n]*\n|\s)*/g, '').trim())
    .filter((s) => s.length > 0 && !s.startsWith('--'));
}

async function main() {
  const mode = process.argv[2] || 'write';
  const source = readFileSync(join(root, 'src/db/schema.sql'), 'utf8');
  const mysql = toMysql(source);
  const outPath = join(root, 'src/db/schema.mysql.sql');
  writeFileSync(outPath, `-- GENERATED by scripts/mysql-schema.mjs from src/db/schema.sql — do not edit by hand.\n${mysql}`);
  console.log(`[mysql-schema] wrote ${outPath}`);
  if (mode !== 'apply') return;

  const { createPool } = await import('mysql2/promise');
  const pool = createPool({
    host: process.env.DB_HOST,
    port: Number(process.env.DB_PORT || 3306),
    user: process.env.DB_USER,
    password: process.env.DB_PASSWORD,
    database: process.env.DB_NAME,
    multipleStatements: false,
    ssl: { rejectUnauthorized: false }
  });
  const statements = splitStatements(mysql);
  let applied = 0;
  for (const statement of statements) {
    try {
      await pool.query(statement);
      applied += 1;
    } catch (err) {
      console.error(`[mysql-schema] FAILED: ${statement.slice(0, 120)}…`);
      throw err;
    }
  }
  console.log(`[mysql-schema] applied ${applied}/${statements.length} statements`);
  await pool.end();
}

if (process.argv[1] && process.argv[1].endsWith('mysql-schema.mjs')) {
  main().catch((err) => {
    console.error('[mysql-schema] error:', err.message);
    process.exit(1);
  });
}
